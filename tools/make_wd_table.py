"""
Writes assets/js/wdtable.js: the van Everdingen-Hurst dimensionless cumulative water influx W_D(t_D)
for radial aquifers at constant terminal pressure, for r_e/r_o = 1.5 ... 50 and an infinite aquifer.

W_D comes from the Laplace-space solution, inverted with the Stehfest algorithm (tools/veh_wd.py), on a log grid
of t_D from 1e-3 to 1e5 (20 points per decade). Near the plateau (r_eD^2 - 1)/2 the Stehfest round-off is about 1e-5,
so each curve is capped at the plateau and made non-decreasing.
Check: the infinite-aquifer curve matches the Edwardson et al. (1962) approximation within 0.1 % for t_D >= 0.01.

Run: python3 tools/make_wd_table.py   (needs numpy and scipy)
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from veh_wd import WD, edwardson

REDS = [1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5, 6, 7, 8, 9, 10, 12, 15, 20, 30, 50, None]
LOG_T0, LOG_T1, PER_DEC = -3.0, 5.0, 20
LOGT = np.linspace(LOG_T0, LOG_T1, int((LOG_T1 - LOG_T0) * PER_DEC) + 1)

def curve(reD):
    lim = None if reD is None else (reD * reD - 1) / 2
    vals = []
    for lt in LOGT:
        v = WD(10 ** lt, reD)
        vals.append(min(v, lim) if lim is not None else v)
    return list(np.maximum.accumulate(np.array(vals)))

def main():
    table = {}
    for reD in REDS:
        table['inf' if reD is None else ('%g' % reD)] = [float('%.6g' % v) for v in curve(reD)]
    inf = table['inf']
    worst = max(abs(inf[i] / edwardson(10 ** LOGT[i]) - 1) for i in range(len(LOGT)) if LOGT[i] >= -2)
    assert worst < 2e-3, worst
    out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'js', 'wdtable.js')
    body = json.dumps({'logT0': LOG_T0, 'perDecade': PER_DEC, 'reD': ['inf' if r is None else r for r in REDS], 'WD': table},
                      separators=(',', ':'))
    with open(out, 'w') as fh:
        fh.write('/*\n * wdtable.js (generated by tools/make_wd_table.py, do not edit)\n'
                 ' * van Everdingen-Hurst W_D(t_D) for radial aquifers, constant terminal pressure.\n'
                 ' * t_D = 10^(logT0 + i / perDecade); one curve per r_e/r_o ("inf" = infinite aquifer).\n */\n'
                 '(function (root, factory) {\n'
                 "  if (typeof module === 'object' && module.exports) module.exports = factory();\n"
                 '  else root.HOWD = factory();\n'
                 "})(typeof self !== 'undefined' ? self : this, function () {\n"
                 "  'use strict';\n  return " + body + ';\n});\n')
    print('wrote', os.path.relpath(out), '| curves:', len(table), '| points per curve:', len(LOGT), '| Edwardson check:', round(worst, 5))

if __name__ == '__main__':
    main()
